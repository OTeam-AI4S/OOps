r"""Build documentation from repository READMEs and explicitly exported operator docstrings."""

from __future__ import annotations

import ast
import posixpath
import re
from collections import defaultdict
from importlib.util import resolve_name
from pathlib import Path, PurePosixPath
from typing import NamedTuple

from mkdocs.config.defaults import MkDocsConfig

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_ROOT = ROOT / "oops"
GENERATED_MARKER = "<!-- This file is generated by docs/gen_pages.py. Do not edit directly. -->"
GENERATED_DOCS_DIR: Path | None = None
MARKDOWN_LINK = re.compile(r"(?<!!)\[([^]]+)]\(([^)]+)\)")
REPOSITORY_BLOB_URL = "https://github.com/OTeam-AI4S/OOps/blob/main"
REPOSITORY_TREE_URL = "https://github.com/OTeam-AI4S/OOps/tree/main"
PROJECT_READMES = {
    ROOT / "examples": "examples/index.md",
}


class Operator(NamedTuple):
    r"""One public export, its owning namespace and its source definition."""

    name: str
    path: str
    group: str
    definition: ast.FunctionDef | ast.ClassDef


def _api_definition(module: str, name: str) -> tuple[str, ast.FunctionDef | ast.ClassDef]:
    r"""Follow source re-exports without importing GPU implementations."""
    module_path = ROOT.joinpath(*module.split("."))
    source = module_path.with_suffix(".py")
    if not source.is_file():
        source = module_path / "__init__.py"
    package = module if source.name == "__init__.py" else module.rpartition(".")[0]
    for node in ast.parse(source.read_text(encoding="utf-8")).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
            return f"{module}.{name}", node
        if isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if (alias.asname or alias.name) == name:
                    target = resolve_name("." * node.level + (node.module or ""), package)
                    return _api_definition(target, alias.name)
    raise ValueError(f"No source definition found for {module}.{name}")


def public_operators() -> list[Operator]:
    r"""Discover the root package's declared API and its canonical source paths."""
    tree = ast.parse((PACKAGE_ROOT / "__init__.py").read_text(encoding="utf-8"))
    exports = next(
        ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets)
    )
    entries = []
    for name in exports:
        if name.startswith("_"):
            continue
        path, definition = _api_definition("oops", name)
        entries.append(Operator(name, path, path.split(".")[1], definition))
    return entries


def group_readmes() -> list[tuple[str, Path]]:
    r"""Find public namespace READMEs, ordered by their human-readable titles."""
    entries = [(path.parent.name, path) for path in PACKAGE_ROOT.glob("*/README.md")]
    return sorted(entries, key=lambda entry: split_readme(entry[1])[0].casefold())


def split_readme(readme: Path) -> tuple[str, str]:
    r"""Separate frontmatter, the first title and the body of a source README."""
    lines = readme.read_text(encoding="utf-8").splitlines()
    if lines and lines[0].strip() == "---":
        for index, line in enumerate(lines[1:], start=1):
            if line.strip() == "---":
                lines = lines[index + 1 :]
                break
    for index, line in enumerate(lines):
        if line.startswith("# "):
            return line[2:].strip(), "\n".join(lines[index + 1 :]).lstrip()
    return readme.parent.name.replace("_", " ").title(), "\n".join(lines).lstrip()


def readme_targets() -> dict[Path, str]:
    r"""Map source README directories and legal files to their generated locations."""
    targets = {ROOT: "index.md", ROOT / "README.zh.md": "index.zh.md", PACKAGE_ROOT: "api.md", **PROJECT_READMES}
    targets.update({readme.parent: f"api/{group}.md" for group, readme in group_readmes()})
    targets.update({path: f"about/{path.name}" for path in (*ROOT.glob("license*.md"), *ROOT.glob("privacy*.md"))})
    return targets


def rewrite_readme_links(body: str, *, readme: Path, page: str) -> str:
    r"""Retain README links on GitHub and resolve them in the generated website."""
    targets = readme_targets()

    def replace(match: re.Match[str]) -> str:
        label, raw = match.groups()
        base = readme.parent
        for prefix in (REPOSITORY_BLOB_URL, REPOSITORY_TREE_URL):
            if raw.startswith(prefix + "/"):
                raw = raw.removeprefix(prefix + "/")
                base = ROOT
                break
        if raw.startswith(("http://", "https://", "mailto:", "#")):
            return match.group(0)
        path, separator, fragment = raw.partition("#")
        source = (base / path).resolve()
        if source.name == "README.md":
            source = source.parent
        if readme == ROOT / "README.md" and source == ROOT / "README.zh.md":
            # Language variants are omitted from the other locale's Markdown files.
            language_target = "zh/" + (f"#{fragment}" if separator else "")
            return f'<a href="{language_target}">{label}</a>'
        if readme == ROOT / "README.zh.md" and source == ROOT and path in {"README.md", "./README.md"}:
            # Keep the language switch outside i18n's same-locale Markdown rewrite.
            language_target = "../" + (f"#{fragment}" if separator else "")
            return f'<a href="{language_target}">{label}</a>'
        target = targets.get(source)
        if target is not None:
            target = posixpath.relpath(target, start=PurePosixPath(page).parent.as_posix())
        elif source.is_relative_to(ROOT):
            prefix = REPOSITORY_TREE_URL if source.is_dir() else REPOSITORY_BLOB_URL
            target = f"{prefix}/{source.relative_to(ROOT).as_posix()}"
        else:
            return match.group(0)
        if separator:
            target += f"#{fragment}"
        return f"[{label}]({target})"

    return MARKDOWN_LINK.sub(replace, body)


def api_directive(entry: Operator) -> str:
    r"""Render one exported operator, retaining inherited constructor handling."""
    reference = f"::: {entry.path}\n    options:\n        heading_level: 3"
    definition = entry.definition
    if (
        isinstance(definition, ast.ClassDef)
        and definition.bases
        and not any(isinstance(member, ast.FunctionDef) and member.name == "__init__" for member in definition.body)
    ):
        reference += (
            "\n        docstring_options:\n"
            "            returns_multiple_items: false\n            warn_unknown_params: false"
        )
    return reference


def readme_page(readme: Path, page: str, entries: list[Operator] | None = None) -> str:
    r"""Combine the readable introduction with the relevant public API docstrings."""
    title, body = split_readme(readme)
    parts = [f"# {title}", rewrite_readme_links(body, readme=readme, page=page)]
    if entries:
        parts += ["## API Reference", "\n\n".join(api_directive(entry) for entry in entries)]
    return "\n\n".join(part for part in parts if part).rstrip() + "\n"


def generated_pages() -> list[tuple[str, str]]:
    r"""Produce the website from READMEs, licenses and root public exports."""
    groups = group_readmes()
    by_group: dict[str, list[Operator]] = defaultdict(list)
    for entry in public_operators():
        by_group[entry.group].append(entry)
    pages = [("index.md", readme_page(ROOT / "README.md", "index.md"))]
    if (ROOT / "README.zh.md").is_file():
        pages.append(("index.zh.md", readme_page(ROOT / "README.zh.md", "index.zh.md")))
    ungrouped = [
        entry for group, entries in by_group.items() if group not in {name for name, _ in groups} for entry in entries
    ]
    overview = readme_page(PACKAGE_ROOT / "README.md", "api.md", ungrouped)
    overview += "\n::: oops\n    options:\n        members: false\n        show_root_heading: false\n"
    pages.append(("api.md", overview))
    for group, readme in groups:
        page = f"api/{group}.md"
        pages.append((page, readme_page(readme, page, by_group[group])))
    for directory, page in PROJECT_READMES.items():
        readme = directory / "README.md"
        if readme.is_file():
            pages.append((page, readme_page(readme, page)))
    for source in sorted((*ROOT.glob("license*.md"), *ROOT.glob("privacy*.md"))):
        pages.append((f"about/{source.name}", source.read_text(encoding="utf-8")))
    return pages


def generated_nav(nav: list) -> list:
    r"""Fill the public operator navigation from the same README sources."""
    result = []
    for item in nav:
        if isinstance(item, dict) and "Operators" in item:
            result.append(
                {
                    "Operators": [
                        "api.md",
                        *({split_readme(readme)[0]: f"api/{group}.md"} for group, readme in group_readmes()),
                    ]
                }
            )
        else:
            result.append(item)
    return result


def cleanup_generated(docs_dir: Path) -> None:
    r"""Remove only marked build output, retaining any authored files."""
    for output in docs_dir.rglob("*.md"):
        if output.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            output.unlink()


def on_config(config: MkDocsConfig) -> MkDocsConfig:
    r"""Materialize generated pages and navigation before the site is rendered."""
    global GENERATED_DOCS_DIR

    docs_dir = Path(config["docs_dir"])
    GENERATED_DOCS_DIR = docs_dir
    cleanup_generated(docs_dir)
    for name, content in generated_pages():
        destination = docs_dir / name
        if destination.exists() and not destination.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(f"{GENERATED_MARKER}\n\n{content.rstrip()}\n", encoding="utf-8")
    if config.get("nav"):
        config["nav"] = generated_nav(config["nav"])
    return config


def on_post_build(config: MkDocsConfig) -> None:
    r"""Leave README sources and static assets after a successful build."""
    cleanup_generated(Path(config["docs_dir"]))


def on_build_error(error: Exception) -> None:
    r"""Clean marked Markdown if a strict documentation build fails."""
    if GENERATED_DOCS_DIR is not None:
        cleanup_generated(GENERATED_DOCS_DIR)
